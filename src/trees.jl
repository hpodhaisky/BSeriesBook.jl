# Chapter 2: rooted trees in the standard numbering.
#
# Every tree except τ is the β-product of a unique pair,
#     t_n = t_{L[n]} ∘ t_{R[n]}     (graft t_{R[n]} onto the root of t_{L[n]}),
# with R[n] ≤ R[L[n]].  A tree is identified with its standard number n.
#
# Book: Section 2.5, Algorithm 3 ("Generate trees") and Algorithm 4
# ("Generate tree functions").

"""
    ProductTable

The table `prod[ℓ, r]` of β-products of Algorithm 3 of the book.  Only pairs with
`order[ℓ] + order[r] ≤ p_max` exist, so the table is stored sparsely.
"""
struct ProductTable
    entries::Dict{Tuple{Int,Int},Int}
end

ProductTable() = ProductTable(Dict{Tuple{Int,Int},Int}())

Base.getindex(P::ProductTable, l::Integer, r::Integer) = P.entries[(l, r)]
Base.setindex!(P::ProductTable, n::Integer, l::Integer, r::Integer) =
    (P.entries[(l, r)] = n)
Base.haskey(P::ProductTable, l::Integer, r::Integer) =
    haskey(P.entries, (l, r))

"""
    TreeTable

All trees up to order `p_max` in the standard numbering, as generated by
Algorithm 3 of the book: `order[n]`, `first[p]`, `last[p]`, `L[n]`,
`R[n]`, `prod[ℓ, r]`.  `L[1]` and `R[1]` are 0, since τ has no factors.

Book: Section 2.5, Algorithm 3 ("Generate trees").
"""
struct TreeTable
    p_max::Int
    order::Vector{Int}
    first::Vector{Int}
    last::Vector{Int}
    L::Vector{Int}
    R::Vector{Int}
    prod::ProductTable
end

Base.length(T::TreeTable) = T.last[T.p_max]
Base.show(io::IO, T::TreeTable) =
    print(io, "TreeTable: ", length(T), " trees up to order ", T.p_max)

"""
    generate_trees(p_max) -> TreeTable

Generate all trees up to order `p_max` in the standard numbering.

Book: Section 2.5, Algorithm 3 ("Generate trees").

```jldoctest
julia> T = generate_trees(4);

julia> T.L[2:8], T.R[2:8]
([1, 2, 1, 3, 4, 1, 1], [1, 1, 2, 1, 1, 3, 4])
```
"""
function generate_trees(p_max::Integer)
    # [book:TRfn10A:begin]
    first = zeros(Int, p_max)
    last = zeros(Int, p_max)
    order = [1]
    L = [0]
    R = [0]
    prod = ProductTable()
    first[1] = 1
    last[1] = 1
    n = 1
    for p in 2:p_max
        first[p] = n + 1
        for r in 1:last[p-1]
            for l in first[p-order[r]]:last[p-order[r]]
                if l == 1 || r <= R[l]
                    n = n + 1
                    prod[l, r] = n
                    push!(L, l)
                    push!(R, r)
                    push!(order, p)
                else
                    prod[l, r] = prod[prod[L[l], r], R[l]]
                end
            end
        end
        last[p] = n
    end
    # [book:TRfn10A:end]
    return TreeTable(p_max, order, first, last, L, R, prod)
end

"""
    TreeFunctions

The tree functions of Algorithm 4 of the book: `Bminus[n]` (the multiplicities of
the trees in B⁻(t_n), as a vector over the trees of lower order),
`factorial[n]` (= t_n!) and `symmetry[n]` (= σ(t_n)).
"""
struct TreeFunctions
    Bminus::Vector{Vector{Int}}
    factorial::Vector{Int}
    symmetry::Vector{Int}
end

pad(m, v) = [v; zeros(Int, m - length(v))]

"""
    tree_functions(T::TreeTable) -> TreeFunctions

Compute `Bminus`, `factorial` and `symmetry` for all trees in `T`.

Book: Section 2.5, Algorithm 4 ("Generate tree functions").
"""
function tree_functions(T::TreeTable)
    (; order, last, L, R) = T
    N = length(T)
    # [book:TRfn20A:begin]
    Bminus = Vector{Vector{Int}}(undef, N)
    factorial = zeros(Int, N)
    symmetry = zeros(Int, N)
    Bminus[1] = Int[]
    factorial[1] = 1
    symmetry[1] = 1
    for n in 2:N
        factorial[n] = div(factorial[L[n]] * factorial[R[n]] * order[n],
                           order[L[n]])
        Bminus[n] = pad(last[order[n]-1], Bminus[L[n]])
        Bminus[n][R[n]] = Bminus[n][R[n]] + 1
        symmetry[n] = symmetry[L[n]] * symmetry[R[n]] * Bminus[n][R[n]]
    end
    # [book:TRfn20A:end]
    return TreeFunctions(Bminus, factorial, symmetry)
end

"""
    Splitting

One splitting of a tree t: `(k, F, m)` stands for the subtree t' = t_k
containing the root, the forest t ∖ t' = F (sorted standard numbers) and
the number m of ways in which this pair arises.
"""
const Splitting = Tuple{Int,Vector{Int},Int}

"""
    Partition

One partition of a tree t into subtrees, obtained by cutting a set of
edges: `(k, F, s, m)` stands for the piece t_k containing the root of t,
the other pieces F (sorted standard numbers), the skeleton t_s (each piece
contracted to a vertex) and the number m of edge sets giving this triple.
"""
const Partition = Tuple{Int,Vector{Int},Int,Int}

# ---------------------------------------------------------------------------
# Convenience: a table together with its tree functions
# ---------------------------------------------------------------------------

"""
    Trees(p_max)

All trees up to order `p_max` with their tree functions.  `T[n]` is the
[`Tree`](@ref) with standard number `n`; iterating over `T` gives all
trees in standard order.
"""
struct Trees
    table::TreeTable
    fns::TreeFunctions
    splits::Base.RefValue{Union{Nothing,Vector{Vector{Splitting}}}}
    parts::Base.RefValue{Union{Nothing,Vector{Vector{Partition}}}}
end

function Trees(p_max::Integer)
    T = generate_trees(p_max)
    return Trees(T, tree_functions(T),
                 Ref{Union{Nothing,Vector{Vector{Splitting}}}}(nothing),
                 Ref{Union{Nothing,Vector{Vector{Partition}}}}(nothing))
end

Base.length(T::Trees) = length(T.table)
Base.show(io::IO, T::Trees) =
    print(io, "Trees: ", length(T), " trees up to order ", T.table.p_max)

"""
    Tree

A rooted tree: its standard number together with the [`Trees`](@ref) it
belongs to.  Obtained as `T[n]`, by iterating over `T`, or from other
trees ([`children`](@ref), [`beta_product`](@ref), [`bplus`](@ref));
[`number`](@ref) gives the standard number.

A tree is not an integer: functions on trees take a `Tree`, so that a
tree cannot be confused with an order, a count or an index.  Two trees
are equal if they have the same standard number (the numbering does not
depend on the maximal order).  A B-series `a` is indexed by trees,
`a[t]` = a(t).
"""
struct Tree
    T::Trees
    n::Int
    function Tree(T::Trees, n::Integer)
        1 <= n <= length(T) || throw(BoundsError(T, n))
        return new(T, n)
    end
end

Base.getindex(T::Trees, n::Integer) = Tree(T, n)
Base.firstindex(::Trees) = 1
Base.lastindex(T::Trees) = length(T)
Base.eltype(::Type{Trees}) = Tree
Base.iterate(T::Trees, n = 1) = n > length(T) ? nothing : (Tree(T, n), n + 1)

"""
    number(t::Tree) -> Int

The standard number n of t = t_n (Algorithm 3 of the book).
"""
number(t::Tree) = t.n

Base.:(==)(s::Tree, t::Tree) = s.n == t.n
Base.hash(t::Tree, h::UInt) = hash(t.n, hash(:Tree, h))
Base.isless(s::Tree, t::Tree) = isless(s.n, t.n)
Base.show(io::IO, t::Tree) = print(io, "t", t.n, " = ", bracket(t))

"""
    order(t::Tree)

Order |t| (number of vertices).  Book: Section 2.5.
"""
order(t::Tree) = t.T.table.order[t.n]

"""
    symmetry(t::Tree)

Symmetry σ(t).  Book: Section 2.5.  Alias: `σ`.
"""
symmetry(t::Tree) = t.T.fns.symmetry[t.n]

"""
    factorial(t::Tree)

The factorial t! of a tree (the array `factorial` of Algorithm 4;
sometimes called the density γ(t)).  A method of `Base.factorial`:
`factorial(5)` is still 120.  Book: Section 2.5.
"""
Base.factorial(t::Tree) = t.T.fns.factorial[t.n]

"""
    alpha(t::Tree)

Number of essentially different ways of labelling t:
α(t) = |t|! / (σ(t) t!).  Book: Section 2.5.  Alias: `α`.
"""
alpha(t::Tree) = div(factorial(big(order(t))), symmetry(t) * factorial(t))

"""
    beta(t::Tree)

β(t) = |t|! / σ(t).  Book: Section 2.5.  Alias: `β`.
"""
beta(t::Tree) = div(factorial(big(order(t))), symmetry(t))

# The symbols of the book, as aliases.
const σ = symmetry
const α = alpha
const β = beta

"""
    trees_of_order(T, p) -> Vector{Tree}

The trees of order `p`, in standard order.
"""
trees_of_order(T::Trees, p::Integer) = [Tree(T, n) for n in tree_range(T, p)]

# Internal: the standard numbers of the trees of order p.
tree_range(T::Trees, p) = T.table.first[p]:T.table.last[p]

"""
    beta_product(s::Tree, t::Tree) -> Tree

The β-product s ∘ t (graft t onto the root of s).  Book: Section 2.2.
"""
function beta_product(s::Tree, t::Tree)
    T = s.T.table.p_max >= t.T.table.p_max ? s.T : t.T
    order(s) + order(t) <= T.table.p_max || throw(DomainError(
        (s, t), "the product has order > $(T.table.p_max)"))
    return Tree(T, T.table.prod[s.n, t.n])
end

"""
    children(t::Tree) -> Vector{Tree}

The trees of B⁻(t), with repetitions, in increasing standard number:
t = [t₁ t₂ ⋯ t_m].
"""
children(t::Tree) = [Tree(t.T, k) for k in child_numbers(t.T, t.n)]

"""
    bplus(T, kids) -> Tree

The tree [t₁ ⋯ t_m] with the given children (B⁺ of a forest); the
inverse of [`children`](@ref).  `bplus(T, Tree[])` is τ.
"""
function bplus(T::Trees, kids::AbstractVector{Tree})
    sum(order, kids; init = 0) < T.table.p_max || throw(DomainError(
        kids, "the tree has order > $(T.table.p_max)"))
    return Tree(T, tree_number(T, [number(k) for k in kids]))
end

"""
    level_sequence(t::Tree) -> Vector{Int}

Level sequence of t (root at level 1, depth-first, children in
decreasing standard number).  Used to compare with RootedTrees.jl.
"""
level_sequence(t::Tree) = level_sequence_numbers(t.T, t.n, 1)

"""
    bracket(t::Tree) -> String

The tree written with B⁺ brackets, e.g. `"[τ[τ]]"`.
"""
bracket(t::Tree) = bracket_string(t.T, t.n)

# ---- internal versions on standard numbers (tables, fast loops) ----------

function child_numbers(T::Trees, n)
    B = T.fns.Bminus[n]
    return [k for k in eachindex(B) for _ in 1:B[k]]
end

function tree_number(T::Trees, kids::AbstractVector{<:Integer})
    n = 1
    for k in sort(kids; rev = true)
        n = T.table.prod[n, k]
    end
    return n
end

function level_sequence_numbers(T::Trees, n, level)
    seq = [level]
    for k in reverse(child_numbers(T, n))
        append!(seq, level_sequence_numbers(T, k, level + 1))
    end
    return seq
end

function bracket_string(T::Trees, n)
    n == 1 && return "τ"
    kids = child_numbers(T, n)
    parts = String[]
    for k in unique(kids)
        m = count(==(k), kids)
        str = bracket_string(T, k)
        push!(parts, m == 1 ? str : str * superscript(m))
    end
    return "[" * join(parts) * "]"
end

function superscript(m::Integer)
    digits = "⁰¹²³⁴⁵⁶⁷⁸⁹"
    return join(digits[nextind(digits, 0, d + 1)] for d in reverse(Base.digits(m)))
end

# ---------------------------------------------------------------------------
# Splittings t' ≤ t, t ∖ t'
# ---------------------------------------------------------------------------

"""
    splittings(T) -> Vector{Vector{Splitting}}

For every tree t_n all pairs (t', t ∖ t'), where t' ≤ t_n is a subtree
containing the root and t ∖ t' the forest of the removed parts, with
multiplicities.  The table does not depend on any B-series; it is built
once per `Trees` object (on first use) by the β-product recursion: for
t_n = t_i ∘ t_j,
- the edge to t_j is cut:  (t_k, F) of t_i gives (t_k, F ∪ {t_j});
- it is kept:  (t_k, F) of t_i and (t_ℓ, G) of t_j give
  (t_k ∘ t_ℓ, F ∪ G).
The pair (t, ∅) is included, the pair (∅, {t}) is not.

Book: Section 2.8 (subtrees), used for the composition (Theorem 3.9).
"""
function splittings(T::Trees)
    T.splits[] === nothing || return T.splits[]
    (; L, R, prod) = T.table
    S = Vector{Vector{Splitting}}(undef, length(T))
    S[1] = [(1, Int[], 1)]
    for n in 2:length(T)
        i, j = L[n], R[n]
        mult = Dict{Tuple{Int,Vector{Int}},Int}()
        add!(k, F, m) = (key = (k, sort(F)); mult[key] = get(mult, key, 0) + m)
        for (k, F, m) in S[i]
            add!(k, [F; j], m)
            for (l, G, m2) in S[j]
                add!(prod[k, l], [F; G], m * m2)
            end
        end
        S[n] = sort!([(k, F, m) for ((k, F), m) in mult])
    end
    T.splits[] = S
    return S
end
